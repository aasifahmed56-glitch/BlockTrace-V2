def build_section_header(title, subtitle=None, accent_color=COLOR_PRIMARY_ACCENT, styles=None):
    """Section title with colored left accent pip and one-line explanatory subtitle."""
    if styles is None:
        styles = build_report_styles()

    pip = Drawing(6, 14)
    pip.add(Line(3, 1, 3, 13, strokeColor=accent_color, strokeWidth=3.5))

    title_p = Paragraph(title, styles['SectionTitle'])

    rows = [[pip, title_p]]
    if subtitle:
        sub_p = Paragraph(subtitle, styles['SectionSubtitle'])
        rows.append(['', sub_p])

    head_table = Table(
        rows,
        colWidths=[0.4 * cm, PRINTABLE_WIDTH - 0.4 * cm]
    )
    head_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 1),
    ]))
    head_table.keepWithNext = True
    head_table.spaceAfter = 4
    return head_table


def build_styled_table(header_row, data_rows, col_widths, accent_color, right_cols=None, styles=None):
    """Consistent table with:
    - Bold header on accent background
    - Zebra striped rows (white / #FAF7F2)
    - Clean border (#E2D7C5)
    - Courier for addresses
    - Right-aligned numbers
    - repeatRows=1 for clean page breaks
    """
    if styles is None:
        styles = build_report_styles()

    right_set = set(right_cols or [])

    # Format header
    fmt_headers = []
    for c_idx, h in enumerate(header_row):
        st = styles['TableHeadRight'] if c_idx in right_set else styles['TableHead']
        fmt_headers.append(Paragraph(h, st))

    table_data = [fmt_headers]

    for r_idx, row in enumerate(data_rows):
        fmt_row = []
        for c_idx, val in enumerate(row):
            if isinstance(val, (Paragraph, list)):
                fmt_row.append(val)
            else:
                s_val = str(val)
                if c_idx in right_set:
                    fmt_row.append(Paragraph(s_val, styles['TableCellRight']))
                elif s_val.startswith("0x") and len(s_val) > 20:
                    fmt_row.append(Paragraph(s_val, styles['TableCellMono']))
                else:
                    fmt_row.append(Paragraph(s_val, styles['TableCell']))
        table_data.append(fmt_row)

    t = Table(table_data, colWidths=col_widths, repeatRows=1)

    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), accent_color),
        ('BOX', (0, 0), (-1, -1), 0.75, COLOR_BORDER),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER_LIGHT),
        ('TOPPADDING', (0, 0), (-1, -1), 4.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4.5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]

    # Zebra striping
    for r in range(1, len(table_data)):
        bg = COLOR_WHITE if (r % 2 == 1) else COLOR_ZEBRA_ROW
        t_style.append(('BACKGROUND', (0, r), (-1, r), bg))

    t.setStyle(TableStyle(t_style))
    return t
