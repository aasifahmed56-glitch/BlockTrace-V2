# ---- Numbered Canvas for "Page X of Y" and Running Headers/Footers ----
class BlockTraceNumberedCanvas(canvas.Canvas):
    """Two-pass canvas that computes total page count dynamically and prints:
    - Running header on Page 2+
    - Running footer with page numbers and short disclaimer on all pages.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()

        # Set document metadata in canvas catalog
        self.setTitle("BlockTrace Forensic Investigation Report")
        self.setAuthor("BlockTrace")
        self.setSubject("Blockchain forensic investigation findings")

        page_w = 21.0 * cm
        page_h = 29.7 * cm
        margin = 1.8 * cm

        # --- Running Header (pages > 1) ---
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 7.5)
            self.setFillColor(COLOR_TEXT_MUTED)
            self.drawString(margin, page_h - 1.2 * cm, "BLOCKTRACE FORENSIC INVESTIGATION REPORT")

            self.setFont("Helvetica-Bold", 7)
            self.setFillColor(COLOR_PRIMARY_ACCENT)
            self.drawRightString(page_w - margin, page_h - 1.2 * cm, "Generated by BlockTrace")

            # Hairline rule below header
            self.setStrokeColor(COLOR_BORDER)
            self.setLineWidth(0.5)
            self.line(margin, page_h - 1.35 * cm, page_w - margin, page_h - 1.35 * cm)

        # --- Running Footer (all pages) ---
        footer_y = 1.2 * cm
        self.setStrokeColor(COLOR_BORDER)
        self.setLineWidth(0.5)
        self.line(margin, footer_y + 0.3 * cm, page_w - margin, footer_y + 0.3 * cm)

        # Left: Platform attribution with dot separator
        self.setFont("Helvetica", 6.5)
        self.setFillColor(COLOR_TEXT_MUTED)
        self.drawString(
            margin,
            footer_y,
            "BlockTrace Forensic Report · Automated Forensic Platform"
        )

        # Right: Page X of Y
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.setFont("Helvetica-Bold", 7.5)
        self.setFillColor(COLOR_PRIMARY_DARK)
        self.drawRightString(page_w - margin, footer_y, page_str)

        self.restoreState()


# ---- Vector Logo Mark (ReportLab Drawing) ----
def create_vector_logo(size=30):
    """Draws a clean network-node icon using pure vector primitives."""
    d = Drawing(size, size)
    # Background circular pill
    d.add(Circle(size / 2, size / 2, size / 2 - 1,
                 fillColor=colors.HexColor('#2E1F18'), strokeColor=COLOR_PRIMARY_ACCENT, strokeWidth=1))

    # Connection lines
    cx, cy = size / 2, size / 2
    d.add(Line(cx, cy, cx - 7, cy + 6, strokeColor=COLOR_ORANGE_DARK, strokeWidth=1.2))
    d.add(Line(cx, cy, cx + 7, cy + 6, strokeColor=COLOR_ORANGE_DARK, strokeWidth=1.2))
    d.add(Line(cx, cy, cx, cy - 8, strokeColor=COLOR_ORANGE_DARK, strokeWidth=1.2))

    # Satellite nodes
    d.add(Circle(cx - 7, cy + 6, 2.5, fillColor=COLOR_BG_CREAM, strokeColor=COLOR_PRIMARY_ACCENT, strokeWidth=0.8))
    d.add(Circle(cx + 7, cy + 6, 2.5, fillColor=COLOR_BG_CREAM, strokeColor=COLOR_PRIMARY_ACCENT, strokeWidth=0.8))
    d.add(Circle(cx, cy - 8, 2.5, fillColor=COLOR_BG_CREAM, strokeColor=COLOR_PRIMARY_ACCENT, strokeWidth=0.8))

    # Central hub node
    d.add(Circle(cx, cy, 3.8, fillColor=COLOR_PRIMARY_ACCENT, strokeColor=COLOR_WHITE, strokeWidth=0.8))
    return d


