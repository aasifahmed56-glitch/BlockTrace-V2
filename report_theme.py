def build_header_band(start_wallet, generated_time_str=None, styles=None, investigation_id=None, target_label=None, data_window=None):
    """Draws the top Page 1 full-width dark brown header band and metadata card."""
    if styles is None:
        styles = build_report_styles()

    if not generated_time_str:
        generated_time_str = datetime.now().strftime("%Y-%m-%d %H:%M UTC")

    logo = create_vector_logo(size=34)

    header_text_cell = [
        Paragraph("BLOCKTRACE", styles['Title']),
        Paragraph("Forensic Investigation Report", styles['Subtitle']),
    ]

    header_table = Table(
        [[logo, header_text_cell]],
        colWidths=[1.4 * cm, 16.0 * cm],
    )
    header_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), COLOR_PRIMARY_DARK),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 12),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
        ('LEFTPADDING', (0, 0), (0, 0), 12),
        ('LEFTPADDING', (1, 0), (1, 0), 8),
        ('RIGHTPADDING', (-1, -1), (-1, -1), 12),
    ]))

    # Metadata grid (Generated, Network, Starting Wallet, optional Target)
    meta_table_style = [
        ('BACKGROUND', (0, 0), (-1, -1), COLOR_BG_CREAM),
        ('BOX', (0, 0), (-1, -1), 0.75, COLOR_BORDER),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, COLOR_BORDER_LIGHT),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]

    if target_label:
        meta_rows = [
            [
                Paragraph(f"<b>GENERATED:</b> {generated_time_str}", styles['TableCell']),
                Paragraph("<b>NETWORK:</b> Ethereum (EVM)", styles['TableCellRight']),
            ],
            [
                Paragraph(f"<b>STARTING WALLET:</b> <font face='Courier' size='8'>{start_wallet}</font>", styles['TableCell']),
                Paragraph(f"<b>TARGET:</b> {target_label}", styles['TableCellRight']),
            ]
        ]
    else:
        meta_rows = [
            [
                Paragraph(f"<b>GENERATED:</b> {generated_time_str}", styles['TableCell']),
                Paragraph("<b>NETWORK:</b> Ethereum (EVM)", styles['TableCellRight']),
            ],
            [
                Paragraph(f"<b>STARTING WALLET:</b> <font face='Courier' size='8'>{start_wallet}</font>", styles['TableCell']),
                "",
            ]
        ]
        meta_table_style.append(('SPAN', (0, 1), (1, 1)))

    if data_window:
        dw_display = data_window.strip()
        if not dw_display.lower().startswith("data window:"):
            dw_display = f"Data window: {dw_display}"
        dw_val = dw_display[len("Data window:"):].strip() if dw_display.lower().startswith("data window:") else dw_display
        row_idx = len(meta_rows)
        meta_rows.append([
            Paragraph(f"<b>DATA WINDOW:</b> {dw_val}", styles['TableCell']),
            "",
        ])
        meta_table_style.append(('SPAN', (0, row_idx), (1, row_idx)))

    if investigation_id:
        meta_rows.append([
            Paragraph(f"<b>INVESTIGATION ID:</b> <font face='Courier' size='7'>{investigation_id}</font>", styles['TableCell']),
            Paragraph("<b>STATUS:</b> Cryptographically Sealed", styles['TableCellRight']),
        ])

    meta_table = Table(
        meta_rows,
        colWidths=[12.2 * cm, 5.2 * cm],
    )
    meta_table.setStyle(TableStyle(meta_table_style))

    return KeepTogether([header_table, Spacer(1, 3), meta_table])


class SectionBlock(Flowable):
    """Binds a section header to a table so that the header is kept with at least
    min_rows data rows, while allowing long tables to split naturally across pages
    with repeatRows=1.
    """
    def __init__(self, header, table, min_rows=3, gap=4):
        super().__init__()
        self.header = header
        self.table = table
        self.min_rows = min_rows
        self.gap = gap

    def wrap(self, availWidth, availHeight):
        hw, hh = self.header.wrap(availWidth, availHeight)
        tw, th = self.table.wrap(availWidth, availHeight - hh - self.gap)
        self.width = max(hw, tw)
        self.height = hh + self.gap + th
        return self.width, self.height

    def split(self, availWidth, availHeight):
        hw, hh = self.header.wrap(availWidth, availHeight)
        remHeight = availHeight - hh - self.gap - 4
        if remHeight <= 0:
            return []

        chunks = self.table.split(availWidth, remHeight)
        if not chunks:
            return []

        first_chunk = chunks[0]
        data_rows_in_chunk = len(first_chunk._cellvalues) - 1
        if data_rows_in_chunk < self.min_rows:
            return []

        gap = self.gap
        class FirstPart(Flowable):
            def __init__(self, h, t):
                super().__init__()
                self.h = h
                self.t = t

            def wrap(self, w, h):
                hw, hh = self.h.wrap(w, h)
                tw, th = self.t.wrap(w, h - hh - gap)
                self.width = max(hw, tw)
                self.height = hh + gap + th
                return self.width, self.height

            def draw(self):
                self.h.canv = self.canv
                hw, hh = self.h.wrap(self.width, self.height)
                self.h.drawOn(self.canv, 0, self.height - hh)
                self.t.canv = self.canv
                tw, th = self.t.wrap(self.width, self.height - hh - gap)
                self.t.drawOn(self.canv, 0, 0)

        fp = FirstPart(self.header, first_chunk)
        return [fp] + list(chunks[1:])

    def draw(self):
        self.header.canv = self.canv
        hw, hh = self.header.wrap(self.width, self.height)
        self.header.drawOn(self.canv, 0, self.height - hh)
        self.table.canv = self.canv
        tw, th = self.table.wrap(self.width, self.height - hh - self.gap)
        self.table.drawOn(self.canv, 0, 0)


def build_kpi_card_row(badges, styles=None):
    """Renders four equal rounded cards: Overall status, Wallets traced, Transactions, Flagged wallets.
    The overall status card uses its severity background.
    """
    if styles is None:
        styles = build_report_styles()

    card_cells = []
    card_widths = []
    card_width = PRINTABLE_WIDTH / len(badges)

    for i, (label, val, col) in enumerate(badges):
        is_overall = (i == 0)

        if is_overall:
            val_style = ParagraphStyle(
                'KPI_Val_Overall',
                parent=styles['Title'],
                fontSize=12,
                leading=14,
                textColor=COLOR_WHITE,
                alignment=1,
            )
            lbl_style = ParagraphStyle(
                'KPI_Lbl_Overall',
                parent=styles['MetaLabel'],
                fontSize=6.5,
                leading=8.5,
                textColor=COLOR_WHITE,
                alignment=1,
            )
        else:
            val_style = ParagraphStyle(
                'KPI_Val',
                parent=styles['Title'],
                fontSize=16,
                leading=18,
                textColor=COLOR_PRIMARY_DARK,
                alignment=1,
            )
            lbl_style = ParagraphStyle(
                'KPI_Lbl',
                parent=styles['MetaLabel'],
                fontSize=6.5,
                leading=8.5,
                textColor=COLOR_TEXT_MUTED,
                alignment=1,
            )

        content = [
            Spacer(1, 3),
            Paragraph(str(val), val_style),
            Spacer(1, 2),
            Paragraph(label.upper(), lbl_style),
            Spacer(1, 3),
        ]
        card_cells.append(content)
        card_widths.append(card_width)

    table = Table([card_cells], colWidths=card_widths)

    table_style = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]

    for i, (_, _, col) in enumerate(badges):
        if i == 0:
            table_style.extend([
                ('BACKGROUND', (i, 0), (i, 0), col),
                ('BOX', (i, 0), (i, 0), 0.75, col),
            ])
        else:
            table_style.extend([
                ('BACKGROUND', (i, 0), (i, 0), COLOR_BG_CREAM),
                ('BOX', (i, 0), (i, 0), 0.75, COLOR_BORDER),
            ])

    table.setStyle(TableStyle(table_style))
    return table


